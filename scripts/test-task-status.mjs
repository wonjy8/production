import assert from 'node:assert/strict';
import {taskStatusGroups,stageGroup,taskGroup,moveTaskGroup,saveTaskStage} from '../production/task-status.js';
import {hubGroup,moduleTemplates,tabTemplates,hubCategories} from '../production/module-hub.js';
assert.deepEqual(taskStatusGroups,['시작 전','진행 중','완료']);
const mapping={'대본 확인':'시작 전','녹음':'진행 중','발행':'완료'},options=Object.keys(mapping);
const task={id:'one',stage:'대본 확인',done:false,title:'팟캐스트'};
assert.equal(taskGroup(task,mapping),'시작 전');
const active=moveTaskGroup(task,'진행 중',options,mapping);assert.equal(active.stage,'녹음');assert.equal(active.done,false);
const done=moveTaskGroup(active,'완료',options,mapping);assert.equal(done.stage,'발행');assert.equal(done.done,true);assert.equal(taskGroup(done,mapping),'완료');
const reopened=moveTaskGroup(done,'시작 전',options,mapping);assert.equal(reopened.done,false);assert.equal(reopened.stage,'대본 확인');
assert.equal(taskGroup({...task,done:true},mapping),'완료');
assert.equal(saveTaskStage({...task,stage:'발행'},task,mapping).done,true);
assert.equal(saveTaskStage({...done,stage:'녹음'},done,mapping).done,false);
assert.equal(stageGroup('기획'),'시작 전');assert.equal(stageGroup('편집'),'진행 중');
assert.equal(stageGroup('발행',mapping),'완료');
assert.equal(tabTemplates[0].id,'blank');
for(const template of moduleTemplates)assert(hubCategories.some(g=>g.id===hubGroup(template)),template.id);
assert.equal(hubGroup(moduleTemplates.find(t=>t.id==='photos')),'media');
assert.equal(hubGroup(moduleTemplates.find(t=>t.id==='tasks')),'schedule');
assert(hubCategories.findIndex(g=>g.id==='media')<hubCategories.findIndex(g=>g.id==='church'));
console.log('PASS fixed task groups, stage mapping, completion/reopening and Hub taxonomy');
